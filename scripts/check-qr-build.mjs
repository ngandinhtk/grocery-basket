import assert from 'node:assert/strict';
import fs from 'node:fs';
import worker from '../dist/server/index.js';
const origin='https://basket.example';
const config=await (await worker.fetch(new Request(origin+'/api/config'),{})).json();
assert.equal(config.coffeeQrImage,null);
const response=await worker.fetch(new Request(origin+'/bank-qr.jpg'),{});
assert.equal(response.status,200);
assert.equal(response.headers.get('content-type'),'image/jpeg');
assert.deepEqual(Buffer.from(await response.arrayBuffer()),fs.readFileSync('public/bank-qr.jpg'));
const page=await (await worker.fetch(new Request(origin),{})).text();
const embeddedQr='data:image/jpeg;base64,'+fs.readFileSync('public/bank-qr.jpg').toString('base64');
assert(page.includes(`<div id="coffee-qr"><img src="${embeddedQr}"`));
assert(!page.includes('coffee-qr-open'));
const donation=JSON.parse(fs.readFileSync('public/coffee-account.json','utf8'));
assert(page.includes('Số tài khoản: '+donation.account));
assert(donation.payload.includes(donation.account));
assert(!page.includes('qrcode.js'));
const bankData=await (await worker.fetch(new Request(origin+'/coffee-bank.js'),{})).text();
assert(bankData.includes(donation.payload));
assert(bankData.includes('data:image/jpeg;base64,'));
console.log('Verified embedded bank QR image, account payload and preserved original JPEG bytes.');
